package com.rescueguide.app.clinical

import com.rescueguide.app.domain.AppModule
import com.rescueguide.app.domain.PatientGroup
import com.rescueguide.app.domain.RescuerType

/**
 * Persian clinical content catalog for the first RescueGuide release.
 * Content is deliberately data-driven so it can be reviewed, localized and tested
 * independently from navigation, audio playback and UI code.
 */
data class ClinicalStepFa(
    val id: String,
    val title: String,
    val instruction: String,
    val repeatable: Boolean = true,
    val timeCritical: Boolean = false
)

data class ClinicalPathwayFa(
    val module: AppModule,
    val patientGroup: PatientGroup,
    val rescuerType: RescuerType,
    val canProvideRescueBreaths: Boolean?,
    val trainedRescuerCount: Int,
    val steps: List<ClinicalStepFa>
)

object ClinicalPathwaysFa {
    private fun s(id: String, title: String, text: String, urgent: Boolean = false) =
        ClinicalStepFa(id, title, text, timeCritical = urgent)

    fun get(
        module: AppModule,
        patient: PatientGroup,
        rescuer: RescuerType,
        canProvideRescueBreaths: Boolean? = null,
        trainedRescuerCount: Int = 1
    ): ClinicalPathwayFa {
        val breaths = canProvideRescueBreaths ?: (rescuer == RescuerType.TRAINED_RESCUER)
        return ClinicalPathwayFa(
        module, patient, rescuer, breaths, trainedRescuerCount,
        when (module) {
            AppModule.BASIC_LIFE_SUPPORT -> bls(patient, rescuer, breaths, trainedRescuerCount)
            AppModule.CHOKING -> choking(patient)
        }
    )
    }

