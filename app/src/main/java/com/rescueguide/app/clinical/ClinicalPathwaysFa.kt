            s("breathing", "تنفس", if (r == RescuerType.TRAINED_RESCUER) "تنفس و نبض براکیال را هم‌زمان حداکثر طی ۱۰ ثانیه بررسی کنید؛ گَس‌گَس طبیعی نیست. اگر نبض وجود ندارد، CPR را آغاز کنید. اگر نبض وجود دارد ولی تنفس طبیعی نیست، هر ۲ تا ۳ ثانیه یک تنفس کمکی بدهید؛ نبض را هر ۲ دقیقه دوباره بررسی کنید. اگر ضربان کمتر از ۶۰ در دقیقه همراه با پرفیوژن ضعیف، با وجود اکسیژن‌رسانی و تهویه مناسب باقی ماند، CPR را آغاز کنید." else "تنفس طبیعی را حداکثر طی ۱۰ ثانیه بررسی کنید. گَس‌گَس طبیعی نیست. امدادگر عادی نبض را بررسی نمی‌کند.", true),
