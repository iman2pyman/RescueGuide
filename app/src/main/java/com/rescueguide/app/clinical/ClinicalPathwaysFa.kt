            s("aed", "دستگاه شوک خودکار", "به‌محض رسیدن دستگاه، آن را روشن کنید و دقیقاً از پیام‌های دستگاه پیروی کنید. هنگام تحلیل ریتم یا شوک، کسی نباید فرد را لمس کند.", true),
