        )
        PatientGroup.INFANT -> listOf(
            s("scene", "ایمنی و پاسخ‌دهی", "ایمنی صحنه را بررسی کنید. کف پای شیرخوار را به‌آرامی تحریک کنید و پاسخ را بررسی کنید.", true),
