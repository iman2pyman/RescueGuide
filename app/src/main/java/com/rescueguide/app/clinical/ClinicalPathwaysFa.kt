            s("continue", "ادامه", "فشارها و تنفس‌ها را با حداقل وقفه ادامه دهید؛ وقفه فشارها کمتر از ۱۰ ثانیه باشد. تا رسیدن کمک تخصصی یا بازگشت نشانه‌های واضح حیات ادامه دهید.", true),
